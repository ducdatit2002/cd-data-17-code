a = 55
b = 5

# Phép cộng: a + b = 55
print(a+b)
# Phép trừ: a - b = 45
print(a-b)
# Phép nhân: a * b = 250
print(a*b)
# Phép chia: a / b = 10 
print(a/b)
# Phép chia lấy dư: a % b 
print(f"lấy dư: {a%b}")
# Phép chia lấy nguyên: a // b 
print(f"lấy nguyên: {a//b}")
# Lũy thừa: a ** b
print(f"Lũy thừa: {a**b}")